// MAC-18: copies the site's made-up show, Saltwater Kitchen, into the iPad app's offline demo
// (iPad/Connector/demo/). Run it again when the site's views change:
//   bun apps/apple/scripts/demo-assets.ts
// The photos are Unsplash License (apps/site/CREDITS.md), which allows this; the views are rendered
// by apps/site/scripts/shots.ts from the starter kit.
import { $ } from "bun";
import { mkdir, rm } from "node:fs/promises";
import { join } from "node:path";
import { SHOWS } from "../../site/src/data/shows";
import views from "../../site/src/data/views.json";

const SHOW = "kitchen";
const site = join(import.meta.dir, "../../site/src/assets");
const out = join(import.meta.dir, "../iPad/Connector/demo");
// Where each photo's subject sits (apps/site/src/lib/views.ts, MEDIA).
const FOCUS: Record<string, string> = { cook: "75% 35%", "guest-cook": "62% 40%", dough: "50% 50%" };

const show = SHOWS.find((s) => s.id === SHOW)!;
const data = views as Record<string, { ground: string; slots: { name: string; x: number; y: number; w: number; h: number; radius: string }[] }>;
const media = new Set<string>();
const list = show.views.map((v) => {
  const rec = data[`${SHOW}-${v.file}`];
  if (!rec) throw new Error(`no ${SHOW}-${v.file} in views.json`);
  return {
    file: v.file,
    name: v.name,
    ground: rec.ground,
    slots: rec.slots.map((s) => {
      const m = v.media?.[s.name];
      if (!m || !FOCUS[m]) throw new Error(`no media or focus for ${v.file}/${s.name}`);
      media.add(m);
      return { ...s, media: m, focus: FOCUS[m] };
    }),
  };
});

await rm(join(out, "views"), { recursive: true, force: true });
await rm(join(out, "media"), { recursive: true, force: true });
await mkdir(join(out, "views"), { recursive: true });
await mkdir(join(out, "media"), { recursive: true });
for (const v of list) await $`cp ${join(site, "views", `${SHOW}-${v.file}.webp`)} ${join(out, "views", `${v.file}.webp`)}`;
for (const m of media) await $`cp ${join(site, "media", `${m}.jpg`)} ${join(out, "media", `${m}.jpg`)}`;

const t = show.text;
await Bun.write(
  join(out, "show.js"),
  `// Generated by apps/apple/scripts/demo-assets.ts from apps/site (Saltwater Kitchen, a made-up show). Don't edit.\n` +
    `window.DEMO_SHOW = ${JSON.stringify({ name: show.name, episode: t.topic, accent: show.accent, start: "teaching", views: list }, null, 2)};\n`,
);
console.log(`demo: ${list.length} views, ${media.size} photos → ${out}`);
